/**
 * Налаштування збірки.
 *
 * Адмін-панель (вузли, зв'язки, редактори двору/будівель/аудиторій, генератор QR)
 * потрібна лише під час розробки. У продакшн-збірці вона повністю вимкнена:
 * `import.meta.env.DEV` === false, тож увесь адмін-код відсікається tree-shaking'ом
 * і не потрапляє у фінальний бандл.
 *
 * Якщо колись знадобиться адмінка на робочому сервері — зберіть з прапорцем:
 *   VITE_ENABLE_ADMIN=true npm run build
 * (але краще так не робити: доступ ніяк не захищений паролем).
 */
export const ADMIN_ENABLED: boolean =
  import.meta.env.DEV || import.meta.env.VITE_ENABLE_ADMIN === 'true';
